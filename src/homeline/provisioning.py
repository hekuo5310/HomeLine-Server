import os
import re
import tempfile
import time

from sqlalchemy import select

from . import models as m


def atomic_write(path, data, mode=0o640):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".homeline-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as out:
            os.fchmod(out.fileno(), mode)
            out.write(data)
            out.flush()
            os.fsync(out.fileno())
        os.replace(temporary, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def render_devices(service):
    parts = ["; Generated by HomeLine. Contains SIP credentials; restrict permissions.\n"]
    now = time.time()
    with service.database.transaction(False) as db:
        devices = db.scalars(
            select(m.Device)
            .join(m.User, m.User.id == m.Device.user_id)
            .where(
                m.User.status == "active",
                m.Device.status == "active",
                m.Device.sip_expires_at > now,
            )
            .order_by(m.Device.id)
        )
        for device in devices:
            active = db.scalar(
                select(m.AuthSession.id)
                .where(
                    m.AuthSession.device_id == device.id,
                    m.AuthSession.revoked.is_(False),
                    m.AuthSession.expires_at > now,
                )
                .limit(1)
            )  # noqa: E712
            if not active:
                continue
            secret = service.vault.decrypt(device.sip_secret)
            if not re.fullmatch("[a-f0-9]{32}", device.id) or not re.fullmatch(
                "[A-Za-z0-9_-]{40,100}", secret
            ):
                raise ValueError("invalid provisioned identity")
            name = "d" + device.id
            parts.append(f"""[{name}]
type=endpoint
transport=homeline-wss
context=homeline-devices
disallow=all
allow=ulaw,alaw
auth={name}-auth
aors={name}
identify_by=auth_username,username
webrtc=yes
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
media_encryption=dtls
dtls_auto_generate_cert=yes
set_var=HOMELINE_DEVICE_ID={device.id}
[{name}-auth]
type=auth
auth_type=userpass
username={name}
password={secret}
realm={service.settings.sip_realm}
[{name}]
type=aor
max_contacts=1
remove_existing=yes
minimum_expiration=30
maximum_expiration=60
default_expiration=60
qualify_frequency=15
""")
    return "\n".join(parts).encode()
